import torch
from transformers import AutoTokenizer, AutoModelForCausalLM

def get_slm(model_name: str):
    """
        Load the small language model (SLM) and its tokenizer.

        Args:
            model_name: Hugging Face model identifier.

        Returns:
            A tuple containing the loaded causal language model and tokenizer.
    """
    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForCausalLM.from_pretrained(
        model_name,
        device_map = "auto",
        dtype = "auto",
    )
    model.eval()
    return model, tokenizer


@torch.inference_mode()
def generate(
        model: AutoModelForCausalLM,
        tokenizer: AutoTokenizer,
        messages: list[dict[str, str]],
        max_new_tokens: int,
        do_sample: bool = False,
) -> str:
    """
        Generate a response from the SLM using chat-formatted messages.

        Args:
            model: Loaded causal language model.
            tokenizer: Tokenizer associated with the model.
            messages: Chat messages containing role and content fields.
            max_new_tokens: Maximum number of tokens to generate.
            do_sample: Whether to use sampling during generation.

        Returns:
            The decoded text generated by the model, excluding input tokens.
    """

    text = tokenizer.apply_chat_template(
        messages,
        tokenize=False,
        add_generation_prompt=True,
    )
    inputs = tokenizer(text, return_tensors="pt").to(model.device)
    outputs = model.generate(**inputs, max_new_tokens=max_new_tokens, do_sample = do_sample)

    # Remove input tokens
    generated_tokens = outputs[0][inputs["input_ids"].shape[1]:]

    response = tokenizer.decode(generated_tokens, skip_special_tokens=True)
    return response
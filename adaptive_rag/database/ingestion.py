from sentence_transformers import SentenceTransformer
import weaviate
from tqdm import tqdm
from weaviate.classes.config import Configure, Property, DataType, VectorDistances
from adaptive_rag.config import COLLECTION_NAME, INGEST_CHUNK_SIZE
from adaptive_rag.embedding.embedder import embed_passages, get_embedding_model
from adaptive_rag.database.weaviate_client import weaviate_session
from adaptive_rag.data.prepare_data import get_data_and_corpus


def create_collection(client: weaviate.WeaviateClient, collection_name: str = COLLECTION_NAME) -> None:
    """
       Create a Weaviate collection for storing corpus passages.

       The collection stores each passage's title and text as properties and
       uses a named self-provided vector, allowing embeddings generated by the
       application to be supplied during ingestion.
       The passage's ``passage_id`` is not a property: it is supplied as the
       object UUID at upload time (see ``batch_upload``).

       Args:
           client: Connected Weaviate client.
           collection_name: Name of the collection to create.
    """
    client.collections.create(
        name = collection_name,
        vector_config = Configure.Vectors.self_provided(name='vector', vector_index_config=Configure.VectorIndex.hnsw(distance_metric=VectorDistances.COSINE)),
        properties = [
            Property(name='title',data_type=DataType.TEXT),
            Property(name='text',data_type=DataType.TEXT)
        ]
    )



def batch_upload(client: weaviate.WeaviateClient, corpus:list[dict[str,str]], vectors: list[list[float]], collection_name: str = COLLECTION_NAME) -> None:
    """
        Upload a batch of corpus passages and their embeddings to Weaviate.

        Each corpus passage is stored with its title and text properties, while
        its corresponding embedding is stored in the collection's named
        ``vector`` vector space. The passage's ``passage_id`` is used as the
        Weaviate object UUID.

        Args:
            client: Connected Weaviate client.
            corpus: Corpus passages to upload. Each passage must contain
                ``passage_id``, ``title`` and ``text`` fields.
            vectors: Embedding vectors corresponding to the corpus passages.
            collection_name: Name of the target Weaviate collection.
    """
    if not corpus:
        return

    if len(corpus) != len(vectors):
        raise ValueError('Number of passages and vectors must match.')

    collection = client.collections.get(collection_name)
    with collection.batch.fixed_size(batch_size=len(corpus)) as batch:
        for doc, vector in zip(corpus, vectors):
            batch.add_object(
                uuid=doc["passage_id"],
                properties={
                    "title": doc["title"],
                    "text": doc["text"]
                },
                vector={
                    "vector": vector
                }
            )
    failed = collection.batch.failed_objects
    if failed:
        for f in failed[:5]:
            print(f"Failed object error: {f.message}")
        raise RuntimeError(f"{len(failed)} objects failed to upload to '{collection_name}'.")


def ingest_corpus(client: weaviate.WeaviateClient, corpus: list[dict[str,str]], model: SentenceTransformer, collection_name: str = COLLECTION_NAME, force_ingest: bool = False) -> None:
    """
        Embed and ingest the retrieval corpus into Weaviate.

        If the collection exists, its object count equals ``len(corpus)``, and
        ``force_ingest`` is False, ingestion is skipped. Any other existing
        collection (count mismatch, or ``force_ingest=True``) is deleted and
        rebuilt from scratch.

        Corpus passages are processed incrementally in batches to avoid holding
        embeddings for the entire corpus in memory. Each passage is represented
        for embedding by its title followed by its text.

        Args:
            client: Connected Weaviate client.
            corpus: Deduplicated corpus passages containing ``passage_id``,
                ``title`` and ``text`` fields.
            model: SentenceTransformer model to use for embedding.
            collection_name: Name of the target Weaviate collection.
            force_ingest: If True, always delete and rebuild the collection.
    """
    if INGEST_CHUNK_SIZE <= 0:
        raise ValueError('INGEST_CHUNK_SIZE must be greater than 0')

    if not corpus:
        raise ValueError("Cannot ingest an empty corpus.")

    exists = client.collections.exists(collection_name)
    if exists:
        count = (client.collections.get(collection_name).aggregate.over_all(total_count=True).total_count)

        if not force_ingest and count == len(corpus):
            print(f"Collection '{collection_name}' complete - ({count} objects). Skipping ingestion.")
            return

        if force_ingest:
            print(f"Force ingestion requested for collection '{collection_name}'. Rebuilding.")
        else:
            print(f"Collection '{collection_name}' incomplete ({count}/{len(corpus)}). Rebuilding.")

        client.collections.delete(collection_name)
        print(f"Existing collection '{collection_name}' deleted")


    create_collection(client, collection_name)
    print(f"Created collection '{collection_name}'")

    for start in tqdm(range(0, len(corpus), INGEST_CHUNK_SIZE), desc="Ingesting"):
        docs = corpus[start: start + INGEST_CHUNK_SIZE]
        texts = [f"{d['title']}\n{d['text']}" for d in docs]
        vectors = embed_passages(model, texts)
        batch_upload(client, docs, vectors, collection_name)

    final_count = (
        client.collections.get(collection_name)
        .aggregate.over_all(total_count=True)
        .total_count
    )

    if final_count != len(corpus):
        raise RuntimeError(f"Ingestion incomplete: expected {len(corpus)} objects, found {final_count}.")

    print(f"Ingestion complete: {final_count} passages.")


def ingest_data() -> None:
    """Build the full corpus and ingest it into Weaviate (occasional setup)."""
    _, _, _, corpus = get_data_and_corpus()
    with weaviate_session() as client:
        embedding_model = get_embedding_model()
        ingest_corpus(client, corpus, embedding_model)
